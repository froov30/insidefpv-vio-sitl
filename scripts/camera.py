#!/usr/bin/env python3
"""The gimbal camera: topics, image decoding, video capture and the pitch command.

The camera is a sensor on a link of the gimbal, so its topic name contains
the whole model path. Nothing here is ROS: the topics are Gazebo transport
topics, read with the gz-transport Python bindings, which is what the
project uses everywhere. The pitch command below is the same story - one
protobuf message on a plain transport topic, so no ROS service is needed
to aim the camera.

The names live in one module because three callers depend on them and a
typo in a topic name fails silently - subscribe() succeeds and just never
calls back:

    record_dataset.py   Task 3 dataset recorder (frames and camera pitch)
    mavlink_link.py     Task 2, optional --video and --gimbal-pitch
    interactive use     gz topic -l | grep camera

The world name is iris_runway: worlds/vio_runway.sdf keeps that name on
purpose so these topic names stay valid.
"""

import threading
import time

import cv2
import numpy as np

import gz.transport13 as gzt
from gz.msgs10.double_pb2 import Double
from gz.msgs10.image_pb2 import Image

CAMERA_BASE = ("/world/iris_runway/model/iris_with_gimbal/model/gimbal/"
               "link/pitch_link/sensor/camera")
IMAGE_TOPIC = f"{CAMERA_BASE}/image"
INFO_TOPIC = f"{CAMERA_BASE}/camera_info"

# The sensor publishes at 10 Hz (see the <update_rate> of the camera in
# worlds/vio_runway.sdf). Recording at the sensor rate keeps the video's
# duration equal to simulated flight time; writing at a higher rate would
# duplicate frames and make the video run slow.
CAMERA_RATE_HZ = 10.0


def image_to_bgr(message):
    """Convert one gz.msgs.Image to an OpenCV BGR array.

    The sensor format is RGB_INT8: 3 bytes per pixel, row-major, top row
    first. Anything else means the sensor definition changed, and reshaping
    it would still succeed and produce a garbled picture, so the payload
    length is checked instead of trusted.

    The protobuf buffer is reused by the transport library once the callback
    returns, so the result is a copy.
    """
    height = message.height
    width = message.width
    expected = width * height * 3
    if len(message.data) != expected:
        raise RuntimeError(
            f"Unexpected image payload {len(message.data)} bytes, "
            f"expected {expected} for {width}x{height} RGB_INT8"
        )
    rgb = np.frombuffer(message.data, dtype=np.uint8).reshape(height, width, 3)
    return rgb[:, :, ::-1].copy()


class VideoRecorder:
    """Writes camera frames to an mp4 while the flight runs.

    Used by mavlink_link.py --video. The encoder is opened on the first
    frame, so the frame size comes from the sensor instead of being assumed.
    Frames are written from the transport callback: at 10 Hz and 640x480 an
    mp4v encode takes a couple of milliseconds, far below the 100 ms frame
    interval, so a separate writer thread would only add a queue that could
    silently drop the frames the video exists to prove.

    The output is a recording of what the aircraft saw, not of a desktop
    window: it is produced the same way whether or not there is a display,
    which is why it can be regenerated by the automated run.
    """

    def __init__(self, path, first_frame_timeout_s=15.0, fps=CAMERA_RATE_HZ):
        self.path = str(path)
        self.fps = fps
        self.frames = 0
        self.writer = None
        self._lock = threading.Lock()
        self._first_frame = threading.Event()
        self.node = gzt.Node()
        self.subscribed = self.node.subscribe(Image, IMAGE_TOPIC, self._on_image)
        if not self.subscribed:
            raise RuntimeError(f"Could not subscribe to {IMAGE_TOPIC}")
        if not self._first_frame.wait(first_frame_timeout_s):
            raise TimeoutError(
                f"No camera frame on {IMAGE_TOPIC} within "
                f"{first_frame_timeout_s:.0f} s. Gazebo must be running with "
                "rendering enabled; scripts/run_gazebo.sh --headless keeps it on."
            )

    def _on_image(self, message):
        frame = image_to_bgr(message)
        with self._lock:
            if self.writer is None:
                height, width = frame.shape[:2]
                # mp4v is the MPEG-4 Part 2 encoder built into OpenCV. H.264
                # would need an extra library; for evidence footage of a
                # 40 s flight the extra quality is not worth the dependency.
                self.writer = cv2.VideoWriter(
                    self.path,
                    cv2.VideoWriter_fourcc(*"mp4v"),
                    self.fps,
                    (width, height),
                )
                if not self.writer.isOpened():
                    raise RuntimeError(f"OpenCV could not open {self.path}")
            self.writer.write(frame)
            self.frames += 1
        self._first_frame.set()

    def close(self):
        """Unsubscribe, flush the encoder, and report the frame count."""
        try:
            self.node.unsubscribe(IMAGE_TOPIC)
        except Exception:  # noqa: BLE001 - teardown must not mask a real error
            pass
        with self._lock:
            if self.writer is not None:
                self.writer.release()
        print(f"Video: {self.frames} frames at {self.fps:.0f} fps -> {self.path}")
        return self.frames


# ---------------------------------------------------------------------------
# Pointing the camera
# ---------------------------------------------------------------------------

# The pitch joint's command topic, named by the model's
# JointPositionController. Only pitch is driven here; roll and yaw stay at
# whatever the model loaded with, and the VIO assumes exactly that.
PITCH_TOPIC = "/gimbal/cmd_pitch"

# 0.7 rad = 40 degrees. Measured on this model: the horizon sits near the
# top of the 640x480 frame, and the ground is visible from directly below
# the aircraft out to about 30 m ahead. 0 leaves the stock level view;
# larger than about 1.2 rad starts to see the underside of the airframe.
PITCH_DOWN_RAD = 0.7

# The controller subscribes after the model loads, and a single publish to
# a topic nobody is listening to yet is lost. Republishing for this long at
# PUBLISH_RATE_HZ guarantees delivery without needing a subscriber-count
# API.
PUBLISH_DURATION_S = 0.5
PUBLISH_RATE_HZ = 20.0


def set_pitch(radians, topic=PITCH_TOPIC,
              duration_s=PUBLISH_DURATION_S, rate_hz=PUBLISH_RATE_HZ):
    """Publish a pitch target and return after the gimbal has had time to move.

    radians is the joint target, not a rate: the joint position controller
    holds it until a new target arrives. Negative values tilt the camera up;
    positive values tilt it down (verified against captured frames).

    Why the camera is pointed down at all: the stock camera looks along the
    horizon. At 5 m altitude a level frame is roughly half sky and half
    runway compressed into a few rows near the horizon, where ground
    features have almost no parallax. Pitching down puts the ground plane
    across most of the image, which is what makes a feature-based VIO work
    in this world.
    """
    node = gzt.Node()
    # advertise() returns the publisher object; Node itself has no
    # publish(). The publisher is kept alive for the whole call so the
    # message is not dropped when the local object goes out of scope.
    publisher = node.advertise(topic, Double)
    message = Double()
    message.data = radians
    sent = 0
    deadline = time.time() + duration_s
    period = 1.0 / rate_hz
    while time.time() < deadline:
        if publisher.publish(message):
            sent += 1
        time.sleep(period)
    if sent == 0:
        raise RuntimeError(
            f"Could not publish to {topic}. Is Gazebo running? "
            "scripts/run_sim.sh starts it."
        )
    # Wait for the joint controller to slew to the target. p_gain is 2 in
    # the gimbal model, so 0.7 rad is reached in well under a second.
    time.sleep(0.5)
    print(f"Gimbal pitch set to {radians:+.2f} rad on {topic} ({sent} messages)")


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Point the Iris gimbal camera")
    parser.add_argument("radians", type=float, nargs="?", default=PITCH_DOWN_RAD,
                        help="pitch target in radians, positive = down")
    set_pitch(parser.parse_args().radians)
