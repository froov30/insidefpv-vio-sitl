#!/usr/bin/env python3
"""Camera topics, image decoding and video capture for the gimbal camera.

The camera is a sensor on a link of the gimbal, so its topic name contains
the whole model path. Nothing here is ROS: the topics are Gazebo transport
topics, read with the gz-transport Python bindings, which is what the
project uses everywhere.

The names live in one module because three callers depend on them and a
typo in a topic name fails silently - subscribe() succeeds and just never
calls back:

    record_dataset.py   Task 3 dataset recorder
    takeoff_land.py     Task 2, optional --video of the flight
    a human running     gz topic -l | grep camera

The world name is iris_runway: worlds/vio_runway.sdf keeps that name on
purpose so these topic names stay valid.
"""

import threading

import cv2
import numpy as np

import gz.transport13 as gzt
from gz.msgs10.image_pb2 import Image

CAMERA_BASE = ("/world/iris_runway/model/iris_with_gimbal/model/gimbal/"
               "link/pitch_link/sensor/camera")
IMAGE_TOPIC = f"{CAMERA_BASE}/image"
INFO_TOPIC = f"{CAMERA_BASE}/camera_info"

# The sensor publishes at 10 Hz (see the <update_rate> of the camera in
# worlds/vio_runway.sdf). Recording at the sensor rate keeps the video's
# duration equal to simulated flight time; writing at a higher rate would
# duplicate frames and make the video run slow.
CAMERA_RATE_HZ = 10.0


def image_to_bgr(message):
    """Convert one gz.msgs.Image to an OpenCV BGR array.

    The sensor format is RGB_INT8: 3 bytes per pixel, row-major, top row
    first. Anything else means the sensor definition changed, and reshaping
    it would still succeed and produce a garbled picture, so the payload
    length is checked instead of trusted.

    The protobuf buffer is reused by the transport library once the callback
    returns, so the result is a copy.
    """
    height = message.height
    width = message.width
    expected = width * height * 3
    if len(message.data) != expected:
        raise RuntimeError(
            f"Unexpected image payload {len(message.data)} bytes, "
            f"expected {expected} for {width}x{height} RGB_INT8"
        )
    rgb = np.frombuffer(message.data, dtype=np.uint8).reshape(height, width, 3)
    return rgb[:, :, ::-1].copy()


class VideoRecorder:
    """Writes camera frames to an mp4 while the flight runs.

    Used by takeoff_land.py --video. The encoder is opened on the first
    frame, so the frame size comes from the sensor instead of being assumed.
    Frames are written from the transport callback: at 10 Hz and 640x480 an
    mp4v encode takes a couple of milliseconds, far below the 100 ms frame
    interval, so a separate writer thread would only add a queue that could
    silently drop the frames the video exists to prove.

    The output is a recording of what the aircraft saw, not of a desktop
    window: it is produced the same way whether or not there is a display,
    which is why it can be regenerated by the automated run.
    """

    def __init__(self, path, first_frame_timeout_s=15.0, fps=CAMERA_RATE_HZ):
        self.path = str(path)
        self.fps = fps
        self.frames = 0
        self.writer = None
        self._lock = threading.Lock()
        self._first_frame = threading.Event()
        self.node = gzt.Node()
        self.subscribed = self.node.subscribe(Image, IMAGE_TOPIC, self._on_image)
        if not self.subscribed:
            raise RuntimeError(f"Could not subscribe to {IMAGE_TOPIC}")
        if not self._first_frame.wait(first_frame_timeout_s):
            raise TimeoutError(
                f"No camera frame on {IMAGE_TOPIC} within "
                f"{first_frame_timeout_s:.0f} s. Gazebo must be running with "
                "rendering enabled; scripts/run_gazebo.sh --headless keeps it on."
            )

    def _on_image(self, message):
        frame = image_to_bgr(message)
        with self._lock:
            if self.writer is None:
                height, width = frame.shape[:2]
                # mp4v is the MPEG-4 Part 2 encoder built into OpenCV. H.264
                # would need an extra library; for evidence footage of a
                # 40 s flight the extra quality is not worth the dependency.
                self.writer = cv2.VideoWriter(
                    self.path,
                    cv2.VideoWriter_fourcc(*"mp4v"),
                    self.fps,
                    (width, height),
                )
                if not self.writer.isOpened():
                    raise RuntimeError(f"OpenCV could not open {self.path}")
            self.writer.write(frame)
            self.frames += 1
        self._first_frame.set()

    def close(self):
        """Unsubscribe, flush the encoder, and report the frame count."""
        try:
            self.node.unsubscribe(IMAGE_TOPIC)
        except Exception:  # noqa: BLE001 - teardown must not mask a real error
            pass
        with self._lock:
            if self.writer is not None:
                self.writer.release()
        print(f"Video: {self.frames} frames at {self.fps:.0f} fps -> {self.path}")
        return self.frames
